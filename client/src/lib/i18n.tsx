interface LocaleContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (chinese: string) => string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      return localStorage.getItem("swahili-ai-language") === "en" ? "en" : "zh";
    } catch {
      return "zh";
    }
  });

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    try {
      localStorage.setItem("swahili-ai-language", nextLanguage);
    } catch {
      // The current choice still applies for this session when storage is unavailable.
    }
  };

  useEffect(() => {
    document.documentElement.lang = language === "en" ? "en" : "zh-CN";
    document.title = APP_TITLE;
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
    if (description) {
      description.content = language === "en"
        ? `${APP_NAME} — ${APP_SLOGAN}. Learn Amharic or Swahili with interactive lessons in Chinese or English.`
        : `${APP_NAME} — ${APP_SLOGAN}。用中文或英语学习阿姆哈拉语与斯瓦希里语。`;
    }
  }, [language]);

  const t = (chinese: string) => language === "zh" ? chinese : translations[chinese] ?? chinese;

  return <LocaleContext.Provider value={{ language, setLanguage, t }}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("useLocale must be used inside LocaleProvider");
  return context;
}
